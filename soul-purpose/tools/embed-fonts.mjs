// Builds www/css/fonts.css with the bundled fonts embedded as data URIs, so they load even when
// index.html is opened straight from disk (browsers block font files on file:// pages).
// Run after changing anything in www/fonts/: node soul-purpose/tools/embed-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const www = path.join(path.dirname(fileURLToPath(import.meta.url)), '../www');
const faces = [
  { family: 'Lilita One', file: 'lilita-one-latin.woff2', weight: '400', license: 'OFL-LilitaOne.txt' },
  { family: 'Nunito', file: 'nunito-latin.woff2', weight: '200 1000', license: 'OFL-Nunito.txt' },
];
let css = '/* Generated by tools/embed-fonts.mjs from www/fonts/. Do not edit by hand.\n' +
  ' * Fonts are licensed under the SIL Open Font License 1.1; see the OFL-*.txt files in www/fonts/. */\n';
for (const f of faces) {
  const b64 = fs.readFileSync(path.join(www, 'fonts', f.file)).toString('base64');
  css += `@font-face {\n  font-family: "${f.family}";\n  src: url("data:font/woff2;base64,${b64}") format("woff2");\n` +
    `  font-weight: ${f.weight}; font-style: normal; font-display: block;\n}\n`;
}
fs.writeFileSync(path.join(www, 'css/fonts.css'), css);
console.log('wrote css/fonts.css', (css.length / 1024).toFixed(0) + ' KB');
