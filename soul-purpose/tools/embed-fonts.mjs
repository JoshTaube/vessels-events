// Builds www/js/fonts.js: the bundled fonts as base64, registered with @font-face when the page loads.
// Why a script and not a CSS file: browsers block font files on pages opened straight from disk (file://),
// and the share card needs the font data itself to draw SVG text onto a canvas.
// Run after changing anything in www/fonts/: node soul-purpose/tools/embed-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const www = path.join(path.dirname(fileURLToPath(import.meta.url)), '../www');
const b64 = (f) => fs.readFileSync(path.join(www, 'fonts', f)).toString('base64');
const js = `/* Generated by tools/embed-fonts.mjs from www/fonts/. Do not edit by hand.
 * Lilita One and Nunito, SIL Open Font License 1.1 (see the OFL-*.txt files in www/fonts/). */
(function (root) {
  'use strict';
  var data = {
    lilita: '${b64('lilita-one-latin.woff2')}',
    nunito: '${b64('nunito-latin.woff2')}'
  };
  var face = function (family, b, weight) {
    return '@font-face{font-family:"' + family + '";src:url(data:font/woff2;base64,' + b + ') format("woff2");font-weight:' + weight + ';font-style:normal;font-display:block}';
  };
  var lilitaCSS = face('Lilita One', data.lilita, '400');
  var css = lilitaCSS + face('Nunito', data.nunito, '200 1000');
  if (root.document) {
    var s = document.createElement('style');
    s.textContent = css;
    (document.head || document.documentElement).appendChild(s);
  }
  root.SP = root.SP || {};
  root.SP.fonts = { css: css, lilitaCSS: lilitaCSS };
})(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(www, 'js/fonts.js'), js);
console.log('wrote js/fonts.js', (js.length / 1024).toFixed(0) + ' KB');
